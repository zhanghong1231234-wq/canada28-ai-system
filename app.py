# 按开奖时间或期号排序
if "开奖时间" in data.columns:
    dates = pd.to_datetime(data["开奖时间"], errors="coerce")
    if dates.notna().all():
        data["_order"] = dates
    else:
        data["_order"] = pd.to_numeric(
            data["期号"], errors="coerce"
        )
else:
    data["_order"] = pd.to_numeric(
        data["期号"], errors="coerce"
    )

data = data.sort_values("_order").reset_index(drop=True)

data["和值"] = (
    data["号码1"] + data["号码2"] + data["号码3"]
).astype(int)

if not data["和值"].between(0, 27).all():
    raise ValueError("发现不合法和值，请检查数据")

# 2. 理论概率分布
theory = np.convolve(
    np.convolve(np.ones(10), np.ones(10)),
    np.ones(10)
) / 1000

# 3. 按时间顺序进行回测
window = 300
prior_strength = 50
minimum_train = 100

actual_results = []
theory_predictions = []
history_predictions = []

for i in range(minimum_train, len(data)):

    # 只使用当前开奖之前的数据
    train = data["和值"].iloc[max(0, i-window):i]
    actual = int(data["和值"].iloc[i])

    counts = (
        train.value_counts()
        .reindex(range(28), fill_value=0)
        .values
    )

    # 历史频率模型，加入理论概率平滑
    prediction = (
        counts + prior_strength * theory
    ) / (len(train) + prior_strength)

    actual_results.append(actual)
    theory_predictions.append(theory.copy())
    history_predictions.append(prediction)

actual_results = np.array(actual_results)
theory_predictions = np.array(theory_predictions)
history_predictions = np.array(history_predictions)

# 4. 计算评分
def evaluate(y, probabilities):
    probabilities = np.clip(probabilities, 1e-12, 1)

    logloss = -np.mean(
        np.log(probabilities[np.arange(len(y)), y])
    )

    one_hot = np.eye(28)[y]

    brier = np.mean(
        np.sum((probabilities - one_hot)**2, axis=1)
    )

    return logloss, brier

theory_log, theory_brier = evaluate(
    actual_results, theory_predictions
)

history_log, history_brier = evaluate(
    actual_results, history_predictions
)

comparison = pd.DataFrame({
    "模型": ["理论概率模型", "历史统计模型"],
    "Log Loss": [theory_log, history_log],
    "Brier Score": [theory_brier, history_brier]
})

